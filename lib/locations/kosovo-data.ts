export function getMunicipality(idOrName: string): Municipality | undefined {
  const query = idOrName.toLowerCase().trim();
  return KOSOVO_MUNICIPALITIES.find(
    (m) => m.id.toLowerCase() === query || m.name.toLowerCase() === query
  );
}

export function searchMunicipalities(query: string): Municipality[] {
  if (!query) return KOSOVO_MUNICIPALITIES;
  const q = query.toLowerCase().trim();
  return KOSOVO_MUNICIPALITIES.filter(
    (m) => m.name.toLowerCase().includes(q) || m.region.toLowerCase().includes(q)
  );
}
