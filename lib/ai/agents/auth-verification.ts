/**
 * PronaX AI — AGENT 9: Authentication, 2FA and Email Verification Agent
 * Menaxhon dhe monitoron të gjitha email-et e autentifikimit dhe verifikimit të përdoruesve.
 * Funksionon në mënyrë të integruar me backend-in deterministik të kodeve OTP (VerificationService).
 */

import { VerificationService } from '@/lib/auth/verification';
import { EmailService } from '@/lib/email/service';
import { EmailDeliveryResult } from '@/lib/email/types';

export type OtpPurpose = 'registration' | 'login' | 'password_reset' | 'email_verify';

export interface OtpRequestResult {
  success: boolean;
  message: string;
  waitSeconds?: number;
  deliveryResult?: EmailDeliveryResult;
  simulatedCode?: string;
  error?: string;
}

export interface OtpVerifyResult {
  success: boolean;
  error?: string;
  remainingAttempts?: number;
  expired?: boolean;
}

export class AuthVerificationAgent {
  static readonly agentId = 'auth_verification';

  /**
   * Sends a deterministic 6-digit cryptographically secure OTP to the user's email.
   * STRICT SECURITY RULES:
   * - OTP code is generated by crypto backend (randomInt), NOT by AI.
   * - Validity is strictly 5 minutes.
   * - Stored as SHA-256 hash.
   * - Never sent to an administrator instead of the actual user.
   * - Never exposed in frontend or AI memory.
   */
  static async sendVerificationOtp(
    email: string,
    purpose: OtpPurpose = 'registration',
    lang: 'sq' | 'en' = 'sq',
    metadata?: { ipAddress?: string; deviceInfo?: string }
  ): Promise<OtpRequestResult> {
    const normalizedEmail = email.toLowerCase().trim();

    // 1. Generate code via deterministic cryptographically secure backend
    const codeResult = await VerificationService.createCode(normalizedEmail);
    if (!codeResult.success || !codeResult.code) {
      return {
        success: false,
        message: codeResult.error || 'Dështoi krijimi i kodit të verifikimit.',
        waitSeconds: codeResult.waitSeconds,
        error: codeResult.error,
      };
    }

    const code = codeResult.code;

    // 2. Dispatch email via EmailService using specialized bilingual template
    let deliveryResult: EmailDeliveryResult;
    try {
      switch (purpose) {
        case 'registration':
          deliveryResult = await EmailService.sendRegistrationOtp(normalizedEmail, code, lang);
          break;
        case 'login':
          deliveryResult = await EmailService.sendLoginOtp(normalizedEmail, code, lang, metadata);
          break;
        case 'password_reset':
          deliveryResult = await EmailService.sendPasswordResetOtp(normalizedEmail, code, lang);
          break;
        case 'email_verify':
          deliveryResult = await EmailService.sendEmailVerifyOtp(normalizedEmail, code, lang);
          break;
        default:
          deliveryResult = await EmailService.sendRegistrationOtp(normalizedEmail, code, lang);
          break;
      }
    } catch (err: any) {
      deliveryResult = {
        success: false,
        error: err.message,
        simulated: false,
        timestamp: new Date().toISOString(),
      };
    }

    // 3. Monitor delivery failures and alert administrator if critical failure occurs
    if (!deliveryResult.success) {
      console.error(`[Agent 9 - Auth] Dështoi dërgimi i OTP për ${normalizedEmail}:`, deliveryResult.error);
      EmailService.sendAdminSecurityAlert({
        title: 'Dështim në Dërgimin e Kodit të Verifikimit (OTP)',
        severity: 'high',
        details: `Nuk u arrit të dërgohej kodi OTP për ${normalizedEmail}. Qëllimi: ${purpose}. Gabimi: ${deliveryResult.error}`,
        affectedEmail: normalizedEmail,
      }).catch(() => {});
    }

    const isSq = lang === 'sq';
    return {
      success: deliveryResult.success,
      message: deliveryResult.success
        ? (isSq
            ? `Kodi me 6 shifra u dërgua me sukses në ${normalizedEmail}. Vlen për 5 minuta.`
            : `A 6-digit code has been sent to ${normalizedEmail}. Valid for 5 minutes.`)
        : (isSq
            ? 'Dështoi dërgimi i email-it të verifikimit. Ju lutem provoni sërish.'
            : 'Failed to send verification email. Please try again.'),
      deliveryResult,
      simulatedCode: deliveryResult.simulated ? code : undefined,
    };
  }

  /**
   * Deterministic server-side verification of OTP code.
   */
  static async verifyOtp(email: string, code: string): Promise<OtpVerifyResult> {
    return VerificationService.verifyCode(email, code);
  }

  /**
   * Checks cooldown and status for an ongoing verification.
   */
  static getStatus(email: string) {
    return VerificationService.getStatus(email);
  }

  /**
   * Autonomous AI troubleshooting assistant for user verification questions.
   */
  static answerTroubleshootingQuery(query: string, lang: 'sq' | 'en' = 'sq'): string {
    const q = query.toLowerCase();
    const isSq = lang === 'sq';

    if (q.includes('spam') || q.includes('nuk erdhi') || q.includes('didn\'t receive') || q.includes('not received') || q.includes('vonuar')) {
      return isSq
        ? `Nëse nuk e keni pranuar kodin 6-shifror me email:\n` +
          `1. Kontrolloni dosjen **Spam / Junk** në email-in tuaj.\n` +
          `2. Verifikoni që keni shkruar saktë adresën e email-it.\n` +
          `3. Prisni 60 sekonda dhe klikoni butonin **"Ridërgo Kodin"**.\n` +
          `4. Sigurohuni që llogaria juaj e email-it ka hapësirë të lirë për të pranuar mesazhe të reja.`
        : `If you haven't received your 6-digit verification code:\n` +
          `1. Check your **Spam / Junk** folder.\n` +
          `2. Ensure you entered your registered email address correctly.\n` +
          `3. Wait 60 seconds and click **"Resend Code"**.\n` +
          `4. Ensure your mailbox has sufficient storage to receive new messages.`;
    }

    if (q.includes('skadoi') || q.includes('expired') || q.includes('5 minut')) {
      return isSq
        ? `Kodet e verifikimit në PronaX kanë vlefshmëri të rreptë prej **5 minutash** për arsye sigurie kibernetike.\n` +
          `Nëse kodi ka skaduar, ju lutem klikoni butonin "Ridërgo Kodin" për të marrë një kod të ri të freskët.`
        : `PronaX verification codes have a strict **5-minute expiration** window for cybersecurity.\n` +
          `If your code has expired, please click "Resend Code" to request a fresh 6-digit code.`;
    }

    if (q.includes('gabim') || q.includes('incorrect') || q.includes('invalid') || q.includes('tentativ')) {
      return isSq
        ? `Për të mbrojtur llogarinë tuaj, keni maksimumi **5 tentativa** për të shënuar kodin e saktë.\n` +
          `Nëse i tejkaloni 5 tentativat, kodi anulohet automatikisht dhe duhet të kërkoni një kod të ri.`
        : `To protect your account, you are allowed up to **5 attempts** to enter the correct code.\n` +
          `If you exceed 5 attempts, the code is invalidated and you must request a new one.`;
    }

    return isSq
      ? `Agjenti i Verifikimit dhe Sigurisë PronaX monitoron të gjitha kodet OTP me 6 shifra.\n` +
        `Kodi dërgohet menjëherë në email-in tuaj dhe është i vlefshëm për 5 minuta. Mos e ndani me askënd.`
      : `PronaX Authentication Agent manages all 6-digit verification codes.\n` +
        `Codes are dispatched immediately to your email and valid for 5 minutes. Never share your code with anyone.`;
  }
}
